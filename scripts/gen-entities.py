"""Writes crates/pestle-html/src/entities.rs from WHATWG's entities.json.

    curl -sSfL https://html.spec.whatwg.org/entities.json -o entities.json
    python3 scripts/gen-entities.py entities.json > crates/pestle-html/src/entities.rs
"""
import json
import sys

entities = json.load(open(sys.argv[1]))
rows = sorted((name[1:], value["characters"]) for name, value in entities.items())
longest = max(len(name) for name, _ in rows)


def lit(s):
    return '"' + "".join(c if c.isalnum() or c in " ;" else "\\u{%x}" % ord(c) for c in s) + '"'


print("// Generated by scripts/gen-entities.py from https://html.spec.whatwg.org/entities.json. Do not edit.")
print()
print("/// The longest entity name, `;` included.")
print("pub(crate) const LONGEST: usize = %d;" % longest)
print()
print("/// Every named character reference without its `&`, sorted; legacy ones also without `;`.")
print("pub(crate) static ENTITIES: [(&str, &str); %d] = [" % len(rows))
for name, chars in rows:
    print("    (%s, %s)," % (lit(name), lit(chars)))
print("];")
