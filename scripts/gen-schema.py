"""Writes crates/pestle-html/src/structured/schema_org.rs from schema.org's vocabulary.

    curl -sSfL https://schema.org/version/latest/schemaorg-current-https-types.csv -o types.csv
    curl -sSfL https://schema.org/version/latest/schemaorg-current-https-properties.csv -o props.csv
    python3 scripts/gen-schema.py types.csv props.csv > crates/pestle-html/src/structured/schema_org.rs
"""
import csv
import sys

PREFIX = "https://schema.org/"
local = lambda iri: iri.strip()[len(PREFIX):] if iri.strip().startswith(PREFIX) else None

types, members = {}, {}
with open(sys.argv[1], newline="") as f:
    for row in csv.DictReader(f):
        name = local(row["id"])
        if not name:
            continue
        enum = [local(x) for x in row["enumerationtype"].split(",") if local(x)]
        parents = [local(x) for x in row["subTypeOf"].split(",") if local(x)]
        if enum:
            members[name] = enum[0]
        else:
            types[name] = parents
props = set()
with open(sys.argv[2], newline="") as f:
    for row in csv.DictReader(f):
        name = local(row["id"])
        if name:
            props.add(name)

print("// Generated by scripts/gen-schema.py from schema.org's vocabulary. Do not edit.")
print()
print("/// Every schema.org type and its direct supertypes, sorted by name.")
print("pub(crate) static TYPES: &[(&str, &[&str])] = &[")
for name in sorted(types):
    print('    ("%s", &[%s]),' % (name, ", ".join('"%s"' % p for p in types[name])))
print("];")
print()
print("/// Every enumeration member and its enumeration, sorted by name (`EventCancelled` → `EventStatusType`).")
print("pub(crate) static MEMBERS: &[(&str, &str)] = &[")
for name in sorted(members):
    print('    ("%s", "%s"),' % (name, members[name]))
print("];")
print()
print("/// Every schema.org property, sorted.")
print("pub(crate) static PROPERTIES: &[&str] = &[")
for name in sorted(props):
    print('    "%s",' % name)
print("];")
